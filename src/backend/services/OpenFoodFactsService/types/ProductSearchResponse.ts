/** -----------------------------
 *  Helpers
 *  ----------------------------- */
const TagArray = array(string());

/** -----------------------------
 *  Environmental Score
 *  ----------------------------- */
const EnvironmentalScoreAdjustments = object({
  origins_of_ingredients: object({
    aggregated_origins: array(
      object({
        epi_score: number(),
        origin: string(),
        percent: number(),
        transportation_score: number(),
      })
    ),
    epi_score: number(),
    epi_value: number(),
    origins_from_categories: TagArray,
    origins_from_origins_field: TagArray,
    transportation_score: number(),
    transportation_scores: record(string(), number()),
    transportation_value: number(),
    transportation_values: record(string(), number()),
    value: number(),
    values: record(string(), number()),
    warning: string().optional(),
  }),
  packaging: object({
    value: number(),
    warning: string(),
  }),
  production_system: object({
    labels: TagArray,
    value: number(),
    warning: string(),
  }),
  threatened_species: object({
    warning: string(),
  }),
});

const EnvironmentalScore = object({
  adjustments: EnvironmentalScoreAdjustments,
  agribalyse: object({
    warning: string(),
  }),
  grade: string(),
  missing: object({
    categories: number(),
    ingredients: number(),
    labels: number(),
    origins: number(),
    packagings: number(),
  }),
  missing_agribalyse_match_warning: number(),
  missing_key_data: number(),
  scores: record(string(), any()),
  status: string(),
});

/** -----------------------------
 *  Nutrition
 *  ----------------------------- */
const Nutrient = object({
  source: string().optional(),
  source_index: number().optional(),
  source_per: string().optional(),
  unit: string(),
  value: number(),
});

const Nutrition = object({
  aggregated_set: object({
    nutrients: object({
      'carbohydrates': Nutrient.optional(),
      'energy': Nutrient.optional(),
      'energy-kcal': Nutrient.optional(),
      'fat': Nutrient.optional(),
      'proteins': Nutrient.optional(),
    }),
    per: string(),
    preparation: string(),
  }),
  input_sets: array(
    object({
      last_updated_t: number(),
      nutrients: record(
        string(),
        object({
          unit: string(),
          value: number(),
          value_string: string().optional(),
        })
      ),
      per: string(),
      per_quantity: number(),
      per_unit: string(),
      preparation: string(),
      source: string(),
    })
  ),
});

/** -----------------------------
 *  Nutriscore
 *  ----------------------------- */
const NutriScoreVersion = object({
  category_available: number(),
  data: record(string(), any()),
  grade: string(),
  nutrients_available: number(),
  nutriscore_applicable: number(),
  nutriscore_computed: number(),
});

const Nutriscore = object({
  2021: NutriScoreVersion,
  2023: NutriScoreVersion,
});

